import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

/*
  The codecs of each version of each API are listed in the index.ts file of their group in src/apis.
  This script generates, out of those lists, the two tables which are used to load the codecs on demand:

  - src/apis/loaders.ts, which is used by the clients.
  - src/apis/deprecated.ts, which keeps the codecs available from the main entry point of the package.

  Run it with: npm run generate:loaders
*/
const groups = ['admin', 'consumer', 'metadata', 'producer', 'security', 'telemetry']
const apisRoot = new URL('../src/apis/', import.meta.url)
const header = '// This file is generated by scripts/generate-api-loaders.ts, do not edit it.\n'

interface Codec {
  name: string
  path: string
  types: string[]
}

/*
  The types a codec exports, whichever way it does it: declared in the file or exported from another one.
  They are needed as the main entry point used to export each codec as a namespace, through which they
  were available.
*/
function listTypes (codecs: Omit<Codec, 'types'>[]): Map<string, string[]> {
  const files = codecs.map(codec => fileURLToPath(new URL(`${codec.path}.ts`, apisRoot)))
  const program = ts.createProgram(files, {
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    target: ts.ScriptTarget.ESNext,
    allowImportingTsExtensions: true,
    noEmit: true,
    skipLibCheck: true,
    types: []
  })
  const checker = program.getTypeChecker()
  const types = new Map<string, string[]>()

  for (const file of files) {
    const module = checker.getSymbolAtLocation(program.getSourceFile(file)!)!
    const names: string[] = []

    for (const exported of checker.getExportsOfModule(module)) {
      const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported

      if (!(symbol.flags & ts.SymbolFlags.Type)) {
        continue
      }

      const declared = checker.getDeclaredTypeOfSymbol(symbol)
      if (declared.aliasTypeArguments?.length || (declared as ts.InterfaceType).typeParameters?.length) {
        throw new Error(`The type ${exported.name} exported by ${file} is generic, which is not supported.`)
      }

      names.push(exported.name)
    }

    types.set(file, names.sort())
  }

  return types
}

export async function listCodecs (): Promise<Codec[]> {
  const codecs: Omit<Codec, 'types'>[] = []

  for (const group of groups) {
    const index = await readFile(new URL(`${group}/index.ts`, apisRoot), 'utf-8')

    for (const [, name, file] of index.matchAll(/^export \* as (\w+) from '\.\/([\w-]+)\.ts'$/gm)) {
      codecs.push({ name, path: `./${group}/${file}` })
    }
  }

  const types = listTypes(codecs)

  return codecs
    .map(codec => ({ ...codec, types: types.get(fileURLToPath(new URL(`${codec.path}.ts`, apisRoot)))! }))
    .sort((a, b) => (a.name < b.name ? -1 : 1))
}

export function generateLoaders (codecs: Codec[]): string {
  return [
    header,
    "import type { API } from './definitions.ts'",
    '',
    'export type APILoader = () => Promise<{ api: API<any, any> }>',
    '',
    '// Where the codecs are, relative to this file and without the extension.',
    'export const apiPaths: Record<string, string> = {',
    codecs.map(codec => `  ${codec.name}: '${codec.path}'`).join(',\n'),
    '}',
    '',
    '// The imports are spelled out so that bundlers can follow them.',
    'export const apiLoaders: Record<string, APILoader> = {',
    codecs.map(codec => `  ${codec.name}: () => import('${codec.path}.ts')`).join(',\n'),
    '}',
    ''
  ].join('\n')
}

export function generateDeprecated (codecs: Codec[]): string {
  const deprecated = '/** @deprecated Import it from `@platformatic/kafka/apis` instead. */'

  return [
    header,
    '/* eslint-disable */',
    '',
    "import { lazy } from './lazy.ts'",
    codecs.map(codec => `import type * as $${codec.name} from '${codec.path}.ts'`).join('\n'),
    '',
    '// These are loaded when they are used for the first time, and will be removed in the next major version.',
    '// Each one comes with a namespace which only has the types of the codec, as they were available that way.',
    codecs
      .map(codec => {
        return [
          '',
          deprecated,
          `export const ${codec.name} = /* @__PURE__ */ lazy<typeof $${codec.name}>('${codec.path}')`,
          deprecated,
          `export declare namespace ${codec.name} {`,
          codec.types.map(type => `  export type ${type} = $${codec.name}.${type}`).join('\n'),
          '}'
        ].join('\n')
      })
      .join('\n'),
    ''
  ].join('\n')
}

export async function generate (): Promise<Map<URL, string>> {
  const codecs = await listCodecs()

  return new Map([
    [new URL('loaders.ts', apisRoot), generateLoaders(codecs)],
    [new URL('deprecated.ts', apisRoot), generateDeprecated(codecs)]
  ])
}

// Returns the generated files which do not match what is in the repository
export async function checkLoaders (): Promise<string[]> {
  const outdated: string[] = []

  for (const [file, contents] of await generate()) {
    if ((await readFile(file, 'utf-8')) !== contents) {
      outdated.push(file.pathname.slice(file.pathname.lastIndexOf('/src/') + 1))
    }
  }

  return outdated
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, contents] of await generate()) {
    await writeFile(file, contents, 'utf-8')
  }
}
