import JSON5 from 'json5'
import { glob, readFile, writeFile } from 'node:fs/promises'
import { basename, resolve } from 'node:path'
import * as codecs from '../src/apis/index.ts'
import { formatOutput } from './utils.ts'

interface VersionBounds {
  minVersion: number
  maxVersion: number
}

async function loadKafkaAPIs (root: string): Promise<Record<string, number>> {
  const apis: Record<string, number> = {}

  for await (const file of glob(resolve(root, 'clients/src/main/resources/common/message/*Request.json'))) {
    const spec = JSON5.parse(await readFile(file, 'utf-8'))
    const key = spec.apiKey as number
    const name = basename(file, 'Request.json')

    apis[name] = key

    if (name === 'ListConfigResources') {
      // The API was renamed in Kafka 4.1.0
      apis['ListClientMetricsResources'] = key
    }
  }

  return apis
}

function addSupportedApis (apisById: [string, number][]): string[] {
  const boundsById = new Map<number, VersionBounds>()

  // Match codecs by wire ID because an API can change names between versions.
  for (const codec of Object.values(codecs)) {
    if (typeof codec !== 'object' || codec === null || !('api' in codec) || typeof codec.api !== 'function') {
      continue
    }

    const { key, version } = codec.api
    const bounds = boundsById.get(key)

    boundsById.set(key, {
      minVersion: Math.min(bounds?.minVersion ?? version, version),
      maxVersion: Math.max(bounds?.maxVersion ?? version, version)
    })
  }

  return apisById.map(([name, id]) => {
    const bounds = boundsById.get(id)
    const supported = bounds !== undefined
    const minVersion = bounds?.minVersion ?? -1
    const maxVersion = bounds?.maxVersion ?? -1

    return `${id}: { name: '${name}', id: ${id}, supported: ${supported}, minVersion: ${minVersion}, maxVersion: ${maxVersion} },`
  })
}

async function main () {
  // Load Kafka API names and IDs
  const kafkaSource = process.argv[2]

  if (!kafkaSource) {
    console.error('Please provide the path to the Kafka source code')
    process.exit(1)
  }

  const apis = await loadKafkaAPIs(resolve(process.cwd(), kafkaSource))
  const apisByKey = Object.entries(apis).sort((a, b) => a[0].localeCompare(b[0]))
  const apisById = Object.entries(apis).sort((a, b) => a[1] - b[1])
  const canonicalApisById = apisById.filter(([name]) => name !== 'ListConfigResources')

  const output = [
    `
// This is autogenerated from the generate:apis script, do not edit manually.

export interface SupportedAPI {
  name: string
  id: number
  supported: boolean
  minVersion: number
  maxVersion: number
}

`
  ]

  // Single constants
  for (const [key, value] of apisById) {
    output.push(`export const ${key}Id = ${value}`)
  }

  // protocolAPIsByName
  output.push('\nexport const protocolAPIsByName: Record<string, number> = Object.freeze({')
  for (const [key, value] of apisByKey) {
    output.push(`${key}: ${value},`)
  }
  output.push('})')

  // protocolAPIsById
  output.push('\nexport const protocolAPIsById: Record<number, string> = Object.freeze({')
  for (const [key, value] of canonicalApisById) {
    output.push(`${value}: '${key}',`)
  }
  output.push('})')

  // supportedApis
  output.push('\nexport const supportedApis: Record<number, SupportedAPI> = Object.freeze({')
  output.push(...addSupportedApis(canonicalApisById))
  output.push('})')

  const destination = resolve(import.meta.dirname, '../src/protocol/apis.ts')
  await writeFile(destination, await formatOutput(output.join('\n'), destination), 'utf-8')
}

await main()
