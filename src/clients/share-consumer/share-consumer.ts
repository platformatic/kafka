import { randomUUID } from 'node:crypto'
import { type CallbackWithPromise, createPromisifiedCallback, kCallbackPromise } from '../../apis/callbacks.ts'
import {
  type ShareGroupHeartbeatRequest,
  type ShareGroupHeartbeatResponse,
  type ShareGroupHeartbeatResponseAssignmentTopicPartition
} from '../../apis/consumer/share-group-heartbeat-v1.ts'
import { type Callback } from '../../apis/definitions.ts'
import { FindCoordinatorKeyTypes } from '../../apis/enumerations.ts'
import { type FindCoordinatorRequest, type FindCoordinatorResponse } from '../../apis/metadata/find-coordinator-v6.ts'
import { createDiagnosticContext, shareConsumerGroupChannel, shareConsumerHeartbeatChannel } from '../../diagnostic.ts'
import { findErrorBy, UserError } from '../../errors.ts'
import { type Connection } from '../../network/connection.ts'
import {
  Base,
  type BaseEvents,
  kAfterCreate,
  kCheckNotClosed,
  kClosed,
  kConnections,
  kFormatValidationErrors,
  kGetApi,
  kGetBootstrapConnection,
  kGetConnection,
  kMetadata,
  kOptions,
  kPerformDeduplicated,
  kPerformWithRetry,
  kPrometheus
} from '../base/base.ts'
import { type GroupAssignment } from '../consumer/types.ts'
import { ensureMetric, type Gauge } from '../metrics.ts'
import { defaultShareHeartbeatInterval } from './options.ts'
import {
  type ShareConsumerGroupPayload,
  type ShareConsumerHeartbeatErrorPayload,
  type ShareConsumerOptions,
  type ShareGroupOptions
} from './types.ts'
import { shareConsumerOptionsValidator, shareGroupOptionsValidator } from './validators.ts'

type ValidateFunction = typeof shareGroupOptionsValidator
type TopicPartitions = ShareGroupHeartbeatResponseAssignmentTopicPartition[]
type MembershipState = 'idle' | 'joining' | 'joined' | 'leaving'

interface ResolvedAssignment {
  assignments: GroupAssignment[]
  complete: boolean
}

export interface ShareConsumerEvents extends BaseEvents {
  'share-consumer:group:join': (payload: ShareConsumerGroupPayload) => void
  'share-consumer:group:leave': (payload: ShareConsumerGroupPayload) => void
  'share-consumer:group:rejoin': (payload: ShareConsumerHeartbeatErrorPayload) => void
  'share-consumer:heartbeat:start': (payload: ShareConsumerGroupPayload) => void
  'share-consumer:heartbeat:end': (payload: ShareConsumerGroupPayload) => void
  'share-consumer:heartbeat:error': (payload: ShareConsumerHeartbeatErrorPayload) => void
}

export class ShareConsumer extends Base<ShareConsumerOptions, ShareConsumerEvents> {
  groupId: string
  // The member id is generated by the client and must be kept for the entire lifetime of the consumer
  memberId: string
  assignments: GroupAssignment[] | null

  #topics: string[]
  #state: MembershipState
  // Incremented when a membership starts or ends, so that the responses of an older one are ignored
  #generation: number
  #memberEpoch: number
  #coordinatorId: number | null
  #heartbeatTimeout: NodeJS.Timeout | null
  #heartbeatInterval: number
  // An assignment received from the coordinator whose topic ids are not all resolved to names yet
  #pendingAssignment: TopicPartitions | null

  constructor (options: ShareConsumerOptions) {
    super(options)
    this.#validate(this[kOptions], shareConsumerOptionsValidator)

    this.groupId = options.groupId
    this.memberId = randomUUID()
    this.assignments = null

    this.#topics = []
    this.#state = 'idle'
    this.#generation = 0
    this.#memberEpoch = 0
    this.#coordinatorId = null
    this.#heartbeatTimeout = null
    this.#heartbeatInterval = defaultShareHeartbeatInterval
    this.#pendingAssignment = null

    if (this[kPrometheus]) {
      ensureMetric<Gauge>(
        this[kPrometheus],
        'Gauge',
        'kafka_share_consumers',
        'Number of active Kafka share consumers'
      ).inc()
    }

    this[kAfterCreate]('share-consumer')
  }

  get memberEpoch (): number {
    return this.#memberEpoch
  }

  get coordinatorId (): number | null {
    return this.#coordinatorId
  }

  isActive (): boolean {
    return super.isActive() && this.#state === 'joined' && this.#memberEpoch > 0
  }

  joinGroup (options: ShareGroupOptions, callback: CallbackWithPromise<string>): void
  joinGroup (options: ShareGroupOptions): Promise<string>
  joinGroup (options: ShareGroupOptions, callback?: CallbackWithPromise<string>): void | Promise<string> {
    if (!callback) {
      callback = createPromisifiedCallback<string>()
    }

    if (this[kCheckNotClosed](callback)) {
      return callback[kCallbackPromise]
    }

    try {
      this.#validate(options, shareGroupOptionsValidator)
    } catch (error) {
      callback(error as Error)
      return callback[kCallbackPromise]
    }

    if (this.#state === 'leaving') {
      callback(new UserError('The consumer is leaving the group.'))
      return callback[kCallbackPromise]
    } else if (this.#state !== 'idle') {
      callback(new UserError('The consumer has already joined the group.'))
      return callback[kCallbackPromise]
    }

    this.#topics = [...options.topics]
    this.#memberEpoch = 0
    this.#state = 'joining'
    const generation = ++this.#generation

    shareConsumerGroupChannel.traceCallback(
      this.#heartbeat,
      1,
      createDiagnosticContext({ client: this, operation: 'joinGroup' }),
      this,
      generation,
      error => {
        if (generation !== this.#generation) {
          callback(error ?? new UserError('The group was left while joining it.'))
          return
        }

        if (error) {
          this.#resetMembership()
          callback(error)
          return
        }

        this.#state = 'joined'
        this.emitWithDebug('share-consumer', 'group:join', this.#groupPayload())
        this.#scheduleHeartbeat()
        callback(null, this.memberId)
      }
    )

    return callback[kCallbackPromise]
  }

  leaveGroup (callback: CallbackWithPromise<void>): void
  leaveGroup (): Promise<void>
  leaveGroup (callback?: CallbackWithPromise<void>): void | Promise<void> {
    if (!callback) {
      callback = createPromisifiedCallback<void>()
    }

    if (this[kCheckNotClosed](callback)) {
      return callback[kCallbackPromise]
    }

    if (this.#state === 'idle') {
      callback(null)
      return callback[kCallbackPromise]
    }

    // Concurrent calls wait for the same request
    this[kPerformDeduplicated](
      'leaveGroup',
      deduplicateCallback => {
        this.#state = 'leaving'
        const generation = ++this.#generation
        this.#cancelHeartbeat()

        shareConsumerGroupChannel.traceCallback(
          this.#performLeaveGroup,
          0,
          createDiagnosticContext({ client: this, operation: 'leaveGroup' }),
          this,
          error => {
            // The consumer was closed in the meanwhile, which also left the group
            if (generation !== this.#generation) {
              deduplicateCallback(null)
              return
            }

            if (error) {
              // The coordinator still considers this a member, so keep the membership alive and let the caller retry
              this.#state = 'joined'
              this.#scheduleHeartbeat()
              deduplicateCallback(error)
              return
            }

            this.#leftGroup()
            deduplicateCallback(null)
          }
        )
      },
      callback
    )

    return callback[kCallbackPromise]
  }

  close (callback: CallbackWithPromise<void>): void
  close (): Promise<void>
  close (callback?: CallbackWithPromise<void>): void | Promise<void> {
    if (!callback) {
      callback = createPromisifiedCallback<void>()
    }

    if (this[kClosed]) {
      callback(null)
      return callback[kCallbackPromise]
    }

    this[kClosed] = true
    this.#cancelHeartbeat()
    this.#generation++

    const closeConnections = () => {
      super.close(error => {
        if (error) {
          this[kClosed] = false
          callback(error)
          return
        }

        if (this[kPrometheus]) {
          ensureMetric<Gauge>(
            this[kPrometheus],
            'Gauge',
            'kafka_share_consumers',
            'Number of active Kafka share consumers'
          ).dec()
        }

        callback(null)
      })
    }

    if (this.#state === 'idle') {
      closeConnections()
      return callback[kCallbackPromise]
    }

    // The client is closed, so leaving can only use the connection to the coordinator which is already open.
    // A leave which is already inflight is sent again, since it might never complete once the connections close.
    // If it fails, the coordinator removes the member when its session times out.
    this.#leaveGroupWhileClosing(() => {
      this.#leftGroup()
      closeConnections()
    })

    return callback[kCallbackPromise]
  }

  #heartbeat (generation: number, callback: CallbackWithPromise<void>): void {
    shareConsumerHeartbeatChannel.traceCallback(
      this.#performHeartbeat,
      1,
      createDiagnosticContext({ client: this, operation: 'shareGroupHeartbeat' }),
      this,
      generation,
      callback
    )
  }

  #performHeartbeat (generation: number, callback: CallbackWithPromise<void>): void {
    // The membership ended while the heartbeat was inflight or waiting for a retry
    const stale = () => this[kClosed] || generation !== this.#generation

    this.emitWithDebug('share-consumer:heartbeat', 'start', this.#groupPayload())

    this.#performGroupOperation<ShareGroupHeartbeatResponse>(
      'shareGroupHeartbeat',
      (connection, groupCallback) => {
        this[kGetApi]<ShareGroupHeartbeatRequest, ShareGroupHeartbeatResponse>('ShareGroupHeartbeat', (error, api) => {
          if (error) {
            groupCallback(error)
            return
          }

          if (stale()) {
            groupCallback(new UserError('The membership ended before sending the heartbeat.'))
            return
          }

          api!(
            connection,
            this.groupId,
            this.memberId,
            this.#memberEpoch,
            this[kOptions].clientRack || null,
            this.#topics,
            groupCallback
          )
        })
      },
      (error, response) => {
        if (stale()) {
          this.emitWithDebug('share-consumer:heartbeat', 'end', this.#groupPayload())
          callback(null)
          return
        }

        if (error) {
          this.#handleHeartbeatError(error)
          callback(error)
          return
        }

        this.#memberEpoch = response!.memberEpoch

        if (response!.heartbeatIntervalMs > 0) {
          this.#heartbeatInterval = response!.heartbeatIntervalMs
        }

        // A null assignment means that it did not change since the previous heartbeat
        if (response!.assignment) {
          this.#pendingAssignment = response!.assignment.topicPartitions
        }

        if (!this.#pendingAssignment) {
          this.emitWithDebug('share-consumer:heartbeat', 'end', this.#groupPayload())
          callback(null)
          return
        }

        this.#resolveAssignment(this.#pendingAssignment, false, (error, resolved) => {
          if (stale()) {
            this.emitWithDebug('share-consumer:heartbeat', 'end', this.#groupPayload())
            callback(null)
            return
          }

          // The membership is not affected, the assignment is resolved again after the next heartbeat
          if (error) {
            this.emitWithDebug('share-consumer:heartbeat', 'error', { ...this.#groupPayload(), error })
            callback(null)
            return
          }

          // Heartbeats are sent one at a time, so no newer assignment can have been received in the meanwhile
          this.assignments = resolved!.assignments
          if (resolved!.complete) {
            this.#pendingAssignment = null
          }

          this.emitWithDebug('share-consumer:heartbeat', 'end', this.#groupPayload())
          callback(null)
        })
      },
      stale
    )
  }

  #handleHeartbeatError (error: Error): void {
    const payload = { ...this.#groupPayload(), error }
    this.emitWithDebug('share-consumer:heartbeat', 'error', payload)

    // The coordinator does not know this member anymore: it must join again with the same member id
    if (
      this.#memberEpoch > 0 &&
      (findErrorBy(error, 'apiId', 'UNKNOWN_MEMBER_ID') || findErrorBy(error, 'apiId', 'FENCED_MEMBER_EPOCH'))
    ) {
      this.#memberEpoch = 0
      this.#pendingAssignment = null
      this.assignments = []
      this.emitWithDebug('share-consumer', 'group:rejoin', payload)
    }
  }

  // Maps the topic ids of an assignment to the topic names, refreshing the metadata once if some are unknown.
  // Partitions of topics which are still unknown are left out and resolved again after the next heartbeat.
  #resolveAssignment (
    topicPartitions: TopicPartitions,
    forceUpdate: boolean,
    callback: Callback<ResolvedAssignment>
  ): void {
    this[kMetadata]({ topics: this.#topics, forceUpdate }, (error, metadata) => {
      if (error) {
        callback(error)
        return
      }

      const topicsById = new Map<string, string>()
      for (const [topic, topicMetadata] of metadata!.topics) {
        topicsById.set(topicMetadata.id, topic)
      }

      const assignments: GroupAssignment[] = []
      for (const assigned of topicPartitions) {
        const topic = topicsById.get(assigned.topicId)

        if (topic) {
          assignments.push({ topic, partitions: assigned.partitions })
        }
      }

      const complete = assignments.length === topicPartitions.length

      if (!complete && !forceUpdate) {
        this.#resolveAssignment(topicPartitions, true, callback)
        return
      }

      callback(null, { assignments, complete })
    })
  }

  #scheduleHeartbeat (): void {
    this.#cancelHeartbeat()
    const generation = this.#generation

    this.#heartbeatTimeout = setTimeout(() => {
      this.#heartbeatTimeout = null

      // Errors have already been emitted: the next heartbeat retries anyway
      this.#heartbeat(generation, () => {
        if (!this[kClosed] && generation === this.#generation) {
          this.#scheduleHeartbeat()
        }
      })
    }, this.#heartbeatInterval)
  }

  #cancelHeartbeat (): void {
    clearTimeout(this.#heartbeatTimeout!)
    this.#heartbeatTimeout = null
  }

  #performLeaveGroup (callback: CallbackWithPromise<void>): void {
    this.#performGroupOperation<ShareGroupHeartbeatResponse>(
      'leaveShareGroup',
      (connection, groupCallback) => {
        this.#sendLeaveGroup(connection, groupCallback)
      },
      error => {
        // A member the coordinator does not know is not part of the group already
        if (findErrorBy(error, 'apiId', 'UNKNOWN_MEMBER_ID') || findErrorBy(error, 'apiId', 'FENCED_MEMBER_EPOCH')) {
          error = null
        }

        callback(error)
      }
    )
  }

  #sendLeaveGroup (connection: Connection, callback: CallbackWithPromise<ShareGroupHeartbeatResponse>): void {
    this[kGetApi]<ShareGroupHeartbeatRequest, ShareGroupHeartbeatResponse>('ShareGroupHeartbeat', (error, api) => {
      if (error) {
        callback(error)
        return
      }

      // A member epoch of -1 leaves the group
      api!(connection, this.groupId, this.memberId, -1, null, null, callback)
    })
  }

  #leaveGroupWhileClosing (callback: () => void): void {
    const timeout = this[kOptions].leaveGroupTimeout
    const connection = this.#getGroupCoordinatorConnection()
    if (timeout === 0 || !connection) {
      callback()
      return
    }

    // Late responses must not run the cleanup twice
    let completed = false
    let timer: NodeJS.Timeout | undefined
    const finish = (): void => {
      if (completed) {
        return
      }

      completed = true
      clearTimeout(timer)
      callback()
    }

    if (timeout !== undefined) {
      timer = setTimeout(finish, timeout)
    }

    this.#sendLeaveGroup(connection, finish)
  }

  #leftGroup (): void {
    this.emitWithDebug('share-consumer', 'group:leave', this.#groupPayload())
    this.#resetMembership()
  }

  #resetMembership (): void {
    this.#state = 'idle'
    this.#memberEpoch = 0
    this.#topics = []
    this.#pendingAssignment = null
    this.assignments = null
  }

  #groupPayload (): ShareConsumerGroupPayload {
    return { groupId: this.groupId, memberId: this.memberId, memberEpoch: this.#memberEpoch }
  }

  #findGroupCoordinator (callback: CallbackWithPromise<number>): void {
    if (this.#coordinatorId !== null) {
      callback(null, this.#coordinatorId)
      return
    }

    shareConsumerGroupChannel.traceCallback(
      this.#performFindGroupCoordinator,
      0,
      createDiagnosticContext({ client: this, operation: 'findGroupCoordinator' }),
      this,
      callback
    )
  }

  #performFindGroupCoordinator (callback: CallbackWithPromise<number>): void {
    this[kPerformDeduplicated](
      'findGroupCoordinator',
      deduplicateCallback => {
        this[kPerformWithRetry]<FindCoordinatorResponse>(
          'findGroupCoordinator',
          retryCallback => {
            this[kGetBootstrapConnection]((error, connection) => {
              if (error) {
                retryCallback(error)
                return
              }

              this[kGetApi]<FindCoordinatorRequest, FindCoordinatorResponse>('FindCoordinator', (error, api) => {
                if (error) {
                  retryCallback(error)
                  return
                }

                api!(connection!, FindCoordinatorKeyTypes.GROUP, [this.groupId], retryCallback)
              })
            })
          },
          (error, response) => {
            if (error) {
              deduplicateCallback(error)
              return
            }

            const groupInfo = response!.coordinators.find(coordinator => coordinator.key === this.groupId)!
            this.#coordinatorId = groupInfo.nodeId
            deduplicateCallback(null, this.#coordinatorId)
          },
          0
        )
      },
      callback
    )
  }

  #performGroupOperation<ReturnType> (
    operationId: string,
    operation: (connection: Connection, callback: CallbackWithPromise<ReturnType>) => void,
    callback: CallbackWithPromise<ReturnType>,
    shouldSkipRetry: () => boolean = () => this[kClosed]
  ): void {
    this[kPerformWithRetry]<ReturnType>(
      operationId,
      retryCallback => {
        this.#findGroupCoordinator((error, coordinatorId) => {
          if (error) {
            retryCallback(error)
            return
          }

          this[kMetadata]({ topics: this.#topics }, (error, metadata) => {
            if (error) {
              retryCallback(this.#handleError(error))
              return
            }

            this[kGetConnection](metadata!.brokers.get(coordinatorId!)!, (error, connection) => {
              if (error) {
                retryCallback(this.#handleError(error))
                return
              }

              operation(connection!, (error, result) => {
                retryCallback(this.#handleError(error), result)
              })
            })
          })
        })
      },
      (error, result) => {
        callback(this.#handleError(error), result)
      },
      0,
      [],
      shouldSkipRetry
    )
  }

  #handleError (error: Error | null): Error | null {
    if (findErrorBy(error, 'hasStaleMetadata', true)) {
      this.clearMetadata()
    } else if (
      findErrorBy(error, 'code', 'PLT_KFK_NETWORK') ||
      findErrorBy(error, 'apiId', 'COORDINATOR_LOAD_IN_PROGRESS') ||
      findErrorBy(error, 'apiId', 'COORDINATOR_NOT_AVAILABLE') ||
      findErrorBy(error, 'apiId', 'NOT_COORDINATOR')
    ) {
      this.#coordinatorId = null
    }

    return error
  }

  #getGroupCoordinatorConnection (): Connection | null {
    if (this.#coordinatorId === null) {
      return null
    }

    const broker = this.currentMetadata?.brokers.get(this.#coordinatorId)
    const connection = broker ? this[kConnections].getEstablishedConnection(broker) : undefined
    return connection?.isConnected() === true ? connection : null
  }

  #validate (target: unknown, validator: ValidateFunction): void {
    if (!validator(target)) {
      throw new UserError(this[kFormatValidationErrors](validator, '/options'))
    }
  }
}
