import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

/*
  The codecs of each version of each API are listed in the index.ts file of their group in src/apis.
  This script generates, out of those lists, the two tables which are used to load the codecs on demand:

  - src/apis/loaders.ts, which is used by the clients.
  - src/apis/deprecated.ts, which keeps the codecs available from the main entry point of the package.

  Run it with: npm run generate:loaders
*/
const groups = ['admin', 'consumer', 'metadata', 'producer', 'security', 'telemetry']
const apisRoot = new URL('../src/apis/', import.meta.url)
const header = '// This file is generated by scripts/generate-api-loaders.ts, do not edit it.\n'

interface Codec {
  name: string
  path: string
}

export async function listCodecs (): Promise<Codec[]> {
  const codecs: Codec[] = []

  for (const group of groups) {
    const index = await readFile(new URL(`${group}/index.ts`, apisRoot), 'utf-8')

    for (const [, name, file] of index.matchAll(/^export \* as (\w+) from '\.\/([\w-]+)\.ts'$/gm)) {
      codecs.push({ name, path: `./${group}/${file}` })
    }
  }

  return codecs.sort((a, b) => (a.name < b.name ? -1 : 1))
}

export function generateLoaders (codecs: Codec[]): string {
  return [
    header,
    "import type { API } from './definitions.ts'",
    '',
    'export type APILoader = () => Promise<{ api: API<any, any> }>',
    '',
    '// Where the codecs are, relative to this file and without the extension.',
    'export const apiPaths: Record<string, string> = {',
    codecs.map(codec => `  ${codec.name}: '${codec.path}'`).join(',\n'),
    '}',
    '',
    '// The imports are spelled out so that bundlers can follow them.',
    'export const apiLoaders: Record<string, APILoader> = {',
    codecs.map(codec => `  ${codec.name}: () => import('${codec.path}.ts')`).join(',\n'),
    '}',
    ''
  ].join('\n')
}

export function generateDeprecated (codecs: Codec[]): string {
  return [
    header,
    '/* eslint-disable @typescript-eslint/consistent-type-imports */',
    '',
    "import { lazy } from './lazy.ts'",
    '',
    '// These are loaded when they are used for the first time, and will be removed in the next major version.',
    codecs
      .map(codec => {
        return [
          '',
          '/** @deprecated Import it from `@platformatic/kafka/apis` instead. */',
          `export const ${codec.name} = /* @__PURE__ */ lazy<typeof import('${codec.path}.ts')>('${codec.path}')`
        ].join('\n')
      })
      .join('\n'),
    ''
  ].join('\n')
}

export async function generate (): Promise<Map<URL, string>> {
  const codecs = await listCodecs()

  return new Map([
    [new URL('loaders.ts', apisRoot), generateLoaders(codecs)],
    [new URL('deprecated.ts', apisRoot), generateDeprecated(codecs)]
  ])
}

// Returns the generated files which do not match what is in the repository
export async function checkLoaders (): Promise<string[]> {
  const outdated: string[] = []

  for (const [file, contents] of await generate()) {
    if ((await readFile(file, 'utf-8')) !== contents) {
      outdated.push(file.pathname.slice(file.pathname.lastIndexOf('/src/') + 1))
    }
  }

  return outdated
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, contents] of await generate()) {
    await writeFile(file, contents, 'utf-8')
  }
}
